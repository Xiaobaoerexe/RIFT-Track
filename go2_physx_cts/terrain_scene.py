"""Upstream terrain dimensions/proportions ported to Isaac Lab mesh generators.

The geometry is generated by Isaac Lab (not byte-identical mjlab triangles).
The differentiable height field is raycast from the very same collision mesh.
"""
import numpy as np
import torch
import warp as wp
from isaaclab.terrains import TerrainImporter,TerrainImporterCfg,TerrainGeneratorCfg
from isaaclab import terrains as tg
from .terrain import HeightField

class CapturedTerrain(TerrainImporter):
    def import_mesh(self,name,mesh):
        self.collision_mesh=mesh
        return super().import_mesh(name,mesh)

def terrain_config():
    gen=TerrainGeneratorCfg(seed=7,size=(12.,12.),border_width=10.,num_rows=5,num_cols=7,curriculum=True,
        horizontal_scale=.1,vertical_scale=.005,slope_threshold=.75,use_cache=False,color_scheme='none',sub_terrains={
        'flat':tg.MeshPlaneTerrainCfg(proportion=.1),
        'stairs':tg.MeshPyramidStairsTerrainCfg(proportion=.2,step_height_range=(.02,.10),step_width=.4,platform_width=1.5,border_width=0.),
        'stairs_inv':tg.MeshInvertedPyramidStairsTerrainCfg(proportion=.2,step_height_range=(.02,.10),step_width=.4,platform_width=1.5,border_width=0.),
        'boxes':tg.MeshRandomGridTerrainCfg(proportion=.15,grid_width=.45,grid_height_range=(.02,.05),platform_width=1.),
        'rough':tg.HfRandomUniformTerrainCfg(proportion=.15,noise_range=(.01,.04),noise_step=.01,border_width=0.),
        'slope':tg.HfPyramidSlopedTerrainCfg(proportion=.1,slope_range=(0.,.3)),
        'slope_inv':tg.HfInvertedPyramidSlopedTerrainCfg(proportion=.1,slope_range=(0.,.3))})
    return TerrainImporterCfg(class_type=CapturedTerrain,prim_path='/World/Ground',terrain_type='generator',terrain_generator=gen,max_init_terrain_level=0,collision_group=-1)

@wp.kernel
def cast_height(mesh:wp.uint64,points:wp.array(dtype=wp.vec3),height:wp.array(dtype=float)):
    i=wp.tid();q=wp.mesh_query_ray(mesh,points[i],wp.vec3(0.,0.,-1.),100.)
    if q.result:height[i]=points[i][2]-q.t
    else:height[i]=0.

def field_from_mesh(terrain,device,res=.05):
    mesh=terrain.collision_mesh;lo,hi=mesh.bounds
    xs=np.arange(lo[0],hi[0]+res,res,dtype=np.float32);ys=np.arange(lo[1],hi[1]+res,res,dtype=np.float32)
    x,y=np.meshgrid(xs,ys);starts=np.stack((x,y,np.full_like(x,hi[2]+2)),axis=-1).reshape(-1,3)
    wm=wp.Mesh(points=wp.array(np.asarray(mesh.vertices,dtype=np.float32),dtype=wp.vec3,device=device),indices=wp.array(np.asarray(mesh.faces,dtype=np.int32).flatten(),dtype=int,device=device))
    h=wp.zeros(len(starts),dtype=float,device=device)
    wp.launch(cast_height,dim=len(starts),inputs=[wm.id,wp.array(starts,dtype=wp.vec3,device=device),h],device=device)
    return HeightField(wp.to_torch(h).reshape(len(ys),len(xs)),(float(lo[0]),float(lo[1])),res)
